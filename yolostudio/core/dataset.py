"""Materialise a project into an ultralytics-ready dataset directory.

Produces the standard layout::

    datasets/<name>/
        data.yaml
        images/{train,val,test}/<image-id>.<ext>
        labels/{train,val,test}/<image-id>.txt

Images are hardlinked when the source lives on the same volume, so a split of a
large dataset costs almost no disk and almost no time. Copying is the fallback.
"""

from __future__ import annotations

import os
import random
import shutil
from dataclasses import dataclass
from pathlib import Path
from typing import Callable, List, Optional, Sequence, Tuple

from .annotations import convert_for_task
from .project import ImageEntry, Project

Progress = Callable[[int, int, str], None]


@dataclass
class ExportResult:
    yaml_path: Path
    root: Path
    counts: dict          # split name -> image count
    instances: int
    skipped_missing: int
    linked: int
    copied: int


def _place(src: Path, dst: Path) -> str:
    """Hardlink ``src`` to ``dst``, falling back to a copy. Returns the mode."""
    if dst.exists():
        try:
            dst.unlink()
        except OSError:
            return "copied"
    try:
        os.link(src, dst)
        return "linked"
    except (OSError, NotImplementedError, AttributeError):
        shutil.copy2(src, dst)
        return "copied"


def split_images(
    entries: Sequence[ImageEntry],
    val_split: float,
    test_split: float,
    seed: int = 0,
) -> Tuple[List[ImageEntry], List[ImageEntry], List[ImageEntry]]:
    """Deterministic random split.

    Guarantees a non-empty validation set whenever there are at least two
    images -- ultralytics needs one to compute mAP, and a silent empty val set
    is a confusing way to find that out.
    """
    items = list(entries)
    random.Random(seed).shuffle(items)
    total = len(items)
    if total == 0:
        return [], [], []

    n_test = int(round(total * max(0.0, test_split)))
    n_val = int(round(total * max(0.0, val_split)))
    if total >= 2:
        n_val = max(1, n_val)
    n_val = min(n_val, total - 1) if total >= 2 else 0
    n_test = min(n_test, total - n_val - 1) if total - n_val > 1 else 0

    test = items[:n_test]
    val = items[n_test:n_test + n_val]
    train = items[n_test + n_val:]
    return train, val, test


def _yaml_escape(text: str) -> str:
    return text.replace("\\", "\\\\").replace('"', '\\"')


def export(
    project: Project,
    task: str,
    name: str = "dataset",
    val_split: float = 0.2,
    test_split: float = 0.0,
    seed: int = 0,
    include_unannotated: bool = False,
    progress: Optional[Progress] = None,
) -> ExportResult:
    """Build a dataset directory for ``task`` ("detect" or "segment")."""
    if not project.classes:
        raise ValueError("Add at least one class before exporting a dataset.")

    pool: List[ImageEntry] = []
    skipped_missing = 0
    for entry in project.images:
        if not entry.exists():
            skipped_missing += 1
            continue
        if include_unannotated or project.is_annotated(entry):
            pool.append(entry)
    if not pool:
        raise ValueError(
            "No annotated images found. Annotate some images, or enable "
            "'include unannotated as background'."
        )

    root = project.datasets_dir / name
    if root.exists():
        shutil.rmtree(root)

    splits = dict(zip(("train", "val", "test"),
                      split_images(pool, val_split, test_split, seed)))

    for split in splits:
        (root / "images" / split).mkdir(parents=True, exist_ok=True)
        (root / "labels" / split).mkdir(parents=True, exist_ok=True)

    total = sum(len(v) for v in splits.values())
    done = 0
    instances = linked = copied = 0

    for split, entries in splits.items():
        for entry in entries:
            src = entry.file
            dst = root / "images" / split / f"{entry.iid}{src.suffix.lower()}"
            mode = _place(src, dst)
            if mode == "linked":
                linked += 1
            else:
                copied += 1

            shapes = convert_for_task(project.shapes_for(entry), task)
            instances += len(shapes)
            label_dst = root / "labels" / split / f"{entry.iid}.txt"
            body = "".join(s.clamped().to_line() + "\n" for s in shapes)
            label_dst.write_text(body, encoding="utf-8")

            done += 1
            if progress is not None:
                progress(done, total, entry.name)

    names_block = "\n".join(
        f'  {i}: "{_yaml_escape(n)}"' for i, n in enumerate(project.classes)
    )
    lines = [
        f"# Generated by YOLO Studio for project {project.name!r}",
        f"path: {root.as_posix()}",
        "train: images/train",
        "val: images/val",
    ]
    if splits["test"]:
        lines.append("test: images/test")
    lines += ["", "names:", names_block, ""]
    yaml_path = root / "data.yaml"
    yaml_path.write_text("\n".join(lines), encoding="utf-8")

    return ExportResult(
        yaml_path=yaml_path,
        root=root,
        counts={k: len(v) for k, v in splits.items()},
        instances=instances,
        skipped_missing=skipped_missing,
        linked=linked,
        copied=copied,
    )
